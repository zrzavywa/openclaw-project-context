#!/usr/bin/env node
// Finds version strings in prose. Volatile states belong in `npm run status`, not in
// documents; an exception list keeps genuine history readable. Read-only.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';

const IGNORE_SECTION = /^##\s+Dokument-Change-Log\s*$/iu;
// "seit 0.7.2" names when something started and cannot go stale.
const HISTORY_MARK = /historisch|überholt|ueberholt|seit\s+0\.\d+\.\d+/iu;
// Table rows carry dated "Stand" columns by convention (sources, drafts); prose is what goes stale.
const TABLE_ROW = /^\s*\|/u;
const VERSION = /\b0\.\d+\.\d+\b/gu;

export function scanText(text) {
  const hits = [];
  let inFence = false;
  let inChangelog = false;
  let inDated = false;
  const lines = text.split('\n');
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    if (/^\s*```/u.test(line)) { inFence = !inFence; continue; }
    if (inFence) continue;
    if (/^#{1,6}\s/u.test(line)) {
      inChangelog = IGNORE_SECTION.test(line);
      // A dated heading opens a section that reports a past observation, not a current state.
      inDated = /\(\d{4}-\d{2}-\d{2}\)/u.test(line);
      continue;
    }
    if (inChangelog || inDated) continue;
    if (HISTORY_MARK.test(line) || TABLE_ROW.test(line)) continue;
    for (const match of line.matchAll(VERSION)) hits.push({ line: index + 1, value: match[0] });
  }
  return hits;
}

function collect(target) {
  const stat = statSync(target);
  if (!stat.isDirectory()) return [target];
  return readdirSync(target)
    .filter((name) => name.endsWith('.md'))
    // KONTEXT.md is generated by the plugin capture; it is not maintained prose.
    .filter((name) => name !== 'KONTEXT.md')
    .map((name) => path.join(target, name));
}

const targets = process.argv.slice(2);
if (targets.length === 0) {
  console.error('check:docs braucht mindestens eine Datei oder ein Verzeichnis.');
  process.exit(2);
}

let findings = 0;
for (const target of targets) {
  for (const file of collect(target)) {
    const hits = scanText(readFileSync(file, 'utf8'));
    for (const hit of hits) {
      findings += 1;
      console.log(`${file}:${hit.line}: Versionsangabe ${hit.value} in Prosa — nutze \`npm run status\` oder kennzeichne sie als historisch.`);
    }
  }
}
console.log(findings === 0 ? 'check:docs PASS' : `check:docs FAIL (${findings} Fundstelle(n))`);
process.exit(findings === 0 ? 0 : 1);
